/** Воронки сделок: 0 (ЧЛ) и 2 (B2C) — частные лица, 1 (ЮЛ) и 3 (B2B) — стройкомпании. */
export const isCompanyFunnel = (categoryId: number | null | undefined) => categoryId === 1 || categoryId === 3;

/** Шаблон под стадию сделки: тип клиента по воронке + ситуация по названию стадии. Не нашёлся — null. */
export function suggestTemplate(list: BigQuestionTemplate[], deal: { stageName: string; categoryId?: number | null } | null | undefined): BigQuestionTemplate | null {
  if (!deal?.stageName) return null;
  const st = deal.stageName.toLowerCase().replace(/ё/g, 'е');
  const company = isCompanyFunnel(deal.categoryId ?? null);
  let want: RegExp | null = null;
  if (/дешевле/.test(st)) want = /дешевле/i;
  else if (company) {
    if (/ждем оплат|подтв/.test(st)) want = /оплат/i;
    else if (/сч[её]т/.test(st)) want = /сч[её]т/i;
    else if (/кп|созвонился|запрос|в работу|дозвонился|обработать/.test(st)) want = /кп/i;
  } else {
    if (/забронировано/.test(st)) want = /подтверд/i;
    else if (/озвучил|созвонился|запрос|в работу|дозвонился|обработать|материал/.test(st)) want = /озвучил|созвонил/i;
  }
  if (!want) return null;
  const audience = company ? /юр|стройкомп|компан/i : /частн|физ/i;
  const norm = (n: string) => n.replace(/ё/g, 'е');
  return list.find(t => want!.test(norm(t.name)) && audience.test(t.name))
    ?? list.find(t => want!.test(norm(t.name)) && !/юр|стройкомп|компан|частн|физ/i.test(t.name))
    ?? null;
}

