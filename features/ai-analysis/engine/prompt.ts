const CLIENT_TYPES = 'Прораб; Строительная организация; Строит себе — начало стройки (брал газобетон/кровлю/утеплитель или ещё планирует баню, сарай); Строит себе — середина/финал; Организация под собственные не строительные нужды.';
const LOST_REASONS = '«Объектов больше нет», «Больше ничего не нужно», «Дорого, предложил другие материалы», «Подвели клиента — не хочет с нами работать».';
const HOUSE: Record<string, string> = { aerated: 'газобетон', frame: 'каркас', any: 'любой' };

function chainText(): string {
  return MATERIAL_CHAIN.map(r => `${HOUSE[r.house] ?? r.house} | ${r.from} → ${r.to} | глубина ${r.depth} | «${r.ask}»`).join('\n');
}

/** Системная часть — неизменна между заказчиками (кэшируется провайдером). */
export function systemPrompt(): string {
  return `# Задача: разбор одного заказчика повторных продаж по его звонкам

Компания продаёт стройматериалы (бетон, газобетон, кровля, утеплитель, пиломатериалы, ЖБИ, нерудка и т.д.). Отдел повторных продаж звонит заказчикам, которые уже покупали, и продаёт им СЛЕДУЮЩИЙ материал на их объект. Нужно: что мы знаем о заказчике из всех его звонков ДО постановки задачи менеджеру, и как менеджеры отработали.

Данные заказчика ниже: сделки (воронка, стадия, даты, сумма, товары, менеджер), «Факты из CRM» (посчитаны кодом — им верь) и ВСЕ расшифрованные звонки по порядку. Расшифровки автоматические: бывают ошибки распознавания, мусор, перепутанные роли «Менеджер/Клиент» (определяй по смыслу: менеджер говорит от имени компании); пометка «без ролей» — роли не размечены. Звонки до ~15 с не расшифровываются. Звонки бывают не с самим заказчиком (снабженцы, водители, коллеги) — отмечай это. Данные обезличены: телефоны, адреса и номера заменены метками вроде [ТЕЛЕФОН] или #, название компании и бренды — [компания].

Типы заказчика (из Битрикса): ${CLIENT_TYPES}
Причины отказа (фиксированные): ${LOST_REASONS}

## Справочник цепочки материалов
Что естественно предлагать после отгрузки группы и вопрос из скрипта. Формат: тип дома | отгружено → что предложить | глубина (0 = самый прямой шаг) | «вопрос».
${chainText()}

## Правила
- Ответ по-русски, строго в формате ниже, заголовки разделов — ровно как написано.
- Не выдумывай: каждое утверждение — из звонков, сделок или фактов CRM; нет данных — так и пиши.
- Цитаты — ДОСЛОВНО из текста звонка, в кавычках «…», до 12 слов, с датой звонка (ДД.ММ). Не пересказывай и не склеивай внутри кавычек. Кавычки «…» — ТОЛЬКО для дословных цитат из звонков и вопросов из справочника; свои формулировки (предлагаемые вопросы, выводы) — без кавычек, курсивом.
- Не приводи телефоны, email, точные адреса, паспортные данные. Имена — можно.

## Формат отчёта (до ~700 слов)

### 1. Кто заказчик
Тип (один из пяти, с обоснованием-цитатой), чем занимается, как общается (сам/через кого), особенности (торгуется, платит наличными, спешит и т.п.).

### 2. Объекты
По каждому объекту: где (посёлок/город), что строит (дом/баня/забор…, тип дома: газобетон/каркас/иное), стадия на момент последнего звонка, что уже купил у нас (по сделкам), что говорил о планах. Хронология стройки по звонкам, коротко.

### 3. Что ему, вероятно, нужно дальше
Конкретные материалы + когда, с опорой (а) на слова заказчика в звонках, (б) на цепочку материалов от последних отгрузок. Какие вопросы из скрипта задать. Что он уже покупал у других / упоминал конкурентов, цены, недовольство.

### 4. Риски и важное перед постановкой задачи
Претензии, срывы доставки, обещания менеджера, договорённости «перезвонить тогда-то», что нельзя забыть.

### 5. Оценка работы менеджера(ов)
По каждому критерию: ДА / НЕТ / ЧАСТИЧНО / НЕПРИМЕНИМО + короткая цитата или дата звонка:
1. Выяснил тип заказчика (строит себе / профи и т.п.)
2. Спросил, что строит, и тип дома
3. Выяснил стадию стройки
4. Предложил следующий материал по цепочке (задал вопрос из скрипта), а не только обслужил входящий заказ
5. Рассказал, что у нас есть и другие материалы (ассортимент)
6. Выяснил, что нужно и когда (сроки)
7. Договорился о следующем шаге (перезвон, КП, дата)
8. При отказе выяснил причину
Правила оценки: ДА — менеджер сделал это сам, по своей инициативе. ЧАСТИЧНО — клиент сам рассказал, менеджер лишь подхватил, или сделано не до конца. НЕТ — возможность была, но не сделано. НЕПРИМЕНИМО — не было повода (п.8 — только если был отказ; п.4–5 — если все звонки служебные/логистика). Будь строг: обслужить входящий заказ — не значит предложить следующий материал.
Затем строка «**Итоговый балл: X из Y = 0,NN**» (ЧАСТИЧНО = 0,5, только применимые); 2–3 сильные стороны, 2–3 упущенные возможности (конкретно: где можно было продать что и не предложили).

### 6. Нарушения и тревожные сигналы
ОБЯЗАТЕЛЬНО по каждому пункту: НАЙДЕНО (дата + цитата) / НЕ НАЙДЕНО.
- Подпись документов за клиента, «распишусь за вас», задним числом, без договора.
- Грубость, мат менеджера, давление, обещания, которые компания не может дать (скидки «от себя», сроки «точно завтра» без основания).
- Обещание клиенту (скидка, компенсация, довоз, перезвон), исполнение которого в данных не видно.
- Отказ/брак без оснований: смотри «Факты из CRM» — если повторная сделка закрыта в отказ, а звонков по ней нет или в последних разговорах клиент не говорил, что ему ничего не нужно, — прямо напиши «ОТКАЗ НЕ ПОДТВЕРЖДЁН ЗВОНКАМИ» и что сделать. Не принимай стадию CRM за правду.
- Клиент недоволен / угрожает уйти / ушёл к конкуренту.

### 7. Качество данных
Сколько звонков реально содержательные, сколько мусор/служебные/не с заказчиком, были ли перепутаны роли, чего не хватает в данных для анализа.

### 8. Памятка менеджеру
То, что менеджер прочитает за 20 секунд перед звонком: 3–5 строк, всего до 60 слов, каждая строка начинается с «— ». Только: что предложить и с какого вопроса зайти; когда клиенту это нужно; главный риск или невыполненное обещание, о котором нельзя забыть. Без цитат, дат звонков, истории, оценки менеджера и нарушений. Нейтрально, без обращения на «ты» или «вы», коротко и по делу.`;
}

const fmtDt = (iso: string) => {
  const d = new Date(new Date(iso).getTime() + 3 * 3600_000).toISOString();
  return `${d.slice(8, 10)}.${d.slice(5, 7)}.${d.slice(0, 4)} ${d.slice(11, 16)}`;
};

/** Пользовательская часть: данные заказчика — без телефонов/адресов/номеров и без названия компании. */
export function userContent(data: ClientCallData): { text: string; maskHits: Record<string, number> } {
  const lines: string[] = [`# Заказчик`, `Тип в карточке клиента: ${data.clientType ?? 'не заполнен'}`,
    `Звонков по сделкам всего: ${data.callsTotal}, состоявшихся: ${data.callsCompleted}, расшифровок в анализе: ${data.calls.length}${data.callsTrimmed ? ` (ещё ${data.callsTrimmed} старых не включены)` : ''}`, '', '## Сделки'];
  for (const d of data.deals) {
    lines.push(`- #${d.dealId} «${d.name ?? ''}» | ${d.funnel ?? ''} | ${d.stage ?? d.stageId ?? ''} | создана ${d.createdAt ?? '—'} | отгружена ${d.deliveredAt ?? '—'} | ${d.amount} ₽ | ${d.group ?? '—'} | ${d.manager ?? '—'}`);
    if (d.products) lines.push(`  товары: ${d.products}`);
  }
  lines.push('', '## Факты из CRM (посчитано кодом)', ...data.facts.map(f => `- ${f}`), '', '## Звонки с расшифровкой');
  for (const c of data.calls) {
    lines.push('', `### ${fmtDt(c.calledAt)} | сделка ${c.dealId} | ${c.direction === 'inbound' ? 'входящий' : c.direction === 'outbound' ? 'исходящий' : c.direction ?? ''} | ${c.durationSec ?? '?'} с | стадия ${c.stage ?? '—'} | ${c.manager ?? '—'}${c.hasRoles ? '' : ' | без ролей'}`, c.text);
  }
  const m = maskPii(lines.join('\n'));
  return { text: maskCompany(m.text, m.hits), maskHits: m.hits };
}
