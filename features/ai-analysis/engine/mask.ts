// Обезличивание расшифровок перед отправкой во внешнюю LLM (решение владельца 22.10: «имена в отрыве
// от телефонов, адресов и прочего — ок»). Режем телефоны, email, карты, ИНН, адреса до улицы/дома,
// номера, продиктованные кусками; имена, посёлки и города оставляем — без них анализ теряет смысл.
// Работает локально, без сети. Адреса — best-effort (регулярки по живой речи ненадёжны), телефоны и
// номера — строго: это то, что нельзя отдавать наружу.
//
// Грабли: `\b` в JS-регулярках не видит кириллицу (буквы — не \w), поэтому границы слов-числительных
// заданы явными (?<![а-яё]) / (?![а-яё]).

const NUM_WORDS = [
  'ноль', 'один', 'одна', 'два', 'две', 'три', 'четыре', 'пять', 'шесть', 'семь', 'восемь', 'девять', 'десять',
  'одиннадцать', 'двенадцать', 'тринадцать', 'четырнадцать', 'пятнадцать', 'шестнадцать', 'семнадцать',
  'восемнадцать', 'девятнадцать', 'двадцать', 'тридцать', 'сорок', 'пятьдесят', 'шестьдесят', 'семьдесят',
  'восемьдесят', 'девяносто', 'сто', 'двести', 'триста', 'четыреста', 'пятьсот', 'шестьсот', 'семьсот',
  'восемьсот', 'девятьсот',
];
const W = `(?:${NUM_WORDS.join('|')})`;
const NW = `(?<![а-яё])${W}(?![а-яё])`;

type Rule = [tag: string, re: RegExp];

const RULES: Rule[] = [
  ['EMAIL', /[\w.+-]+@[\w-]+\.[\w.]+/g],
  ['ТЕЛЕФОН', /(?:\+7|\b8)[\s\-()]*\d{3}[\s\-()]*\d{3}[\s\-]*\d{2}[\s\-]*\d{2}\b/g],
  ['ТЕЛЕФОН', /\b9\d{2}[\s-]?\d{3}[\s-]?\d{2}[\s-]?\d{2}\b/g],
  // В т.ч. частично скрытые распознавателем: «8-911-***-**-12».
  ['ТЕЛЕФОН', /\b\d[\d*\s\-()]{8,}[\d*]\b/g],
  // Продиктованные группами цифры (карта, телефон, паспорт, счёт).
  ['НОМЕР', /\b\d{2,4}(?:[\s-]\d{2,4}){2,}\b/g],
  // Номер словами: «восемь девятьсот одиннадцать …» — шесть и больше числительных подряд.
  ['НОМЕР', new RegExp(`(?:${NW}[\\s,.\\-—]+){5,}${NW}`, 'gi')],
  ['КАРТА', /\b\d{16}\b/g],
  ['ИНН', /\b\d{10}(?:\d{2})?\b/g],
  ['АДРЕС', /(?:улиц[аеуы]|ул\.|проспект\w*|пр-т|переул\w*|шоссе|набережн\w*|бульвар\w*)\s+[^\n,.;]{2,40}?(?:,?\s*(?:дом|д\.)?\s*\d+[а-я]?(?:\s*(?:корп\w*|к\.|стр\w*)\s*\d+)?(?:,?\s*кв\w*\.?\s*\d+)?)?(?=[\s,.;]|$)/gi],
  ['КВАРТИРА', /(?<![а-яё])(?:квартир\w*|кв\.)\s*\d+/gi],
];

/** Сколько цифр/звёздочек должно быть в «номере», чтобы его резать: даты, размеры, цены — короче. */
const MIN_NUMBER_DIGITS = 9;
const ISO_DATE = /^\d{4}-\d{2}-\d{2}/;

// Номер, продиктованный кусками в нескольких репликах («запиши: девятьсот пять… пятьдесят семь…»):
// после слова-триггера в окне TRIGGER_WINDOW знаков режем все цифры и числительные, если их там
// не меньше MIN_PIECES (две — это ещё цена «22 400», три и больше — уже номер).
const TRIGGER = /(номер|телефон|запиш|записыва|карт[аеуы]|по карте|банк|сбер|тинькоф|т-банк|перевед|скинь|продиктую|диктую)/gi;
const NUM_TOKEN = new RegExp(`\\d[\\d*]*|${NW}`, 'gi');
const TRIGGER_WINDOW = 150;
const MIN_PIECES = 3;

export interface MaskResult { text: string; hits: Record<string, number> }

export function maskPii(input: string): MaskResult {
  const hits: Record<string, number> = {};
  const hit = (tag: string) => { hits[tag] = (hits[tag] ?? 0) + 1; };
  let t = input;

  for (const [tag, re] of RULES) {
    t = t.replace(re, m => {
      if ((tag === 'НОМЕР' || tag === 'ТЕЛЕФОН') && /\d/.test(m)
        && (m.replace(/[^\d*]/g, '').length < MIN_NUMBER_DIGITS || ISO_DATE.test(m))) return m;
      hit(tag);
      return `[${tag}]`;
    });
  }

  // Служебные строки (заголовки звонков «### дата | сделка …», строки сделок «- #…») не трогаем:
  // в них даты и номера сделок, а окно вокруг триггера не должно в них заходить.
  t = t.split(/^((?:#{2,}|- #).*)$/m).map((part, i) => (i % 2 ? part : maskPieces(part, hit))).join('');

  return { text: t, hits };
}

/** Окна ±TRIGGER_WINDOW вокруг слов-триггеров (номер диктуют и до, и после «это банк»). */
function maskPieces(text: string, hit: (tag: string) => void): string {
  const wins: [number, number][] = [];
  for (const m of text.matchAll(TRIGGER)) {
    const a = Math.max(0, m.index! - TRIGGER_WINDOW), b = Math.min(text.length, m.index! + m[0].length + TRIGGER_WINDOW);
    const last = wins[wins.length - 1];
    if (last && a <= last[1]) last[1] = Math.max(last[1], b); else wins.push([a, b]);
  }
  if (!wins.length) return text;
  let out = '', pos = 0;
  for (const [a, b] of wins) {
    const win = text.slice(a, b);
    out += text.slice(pos, a);
    if ((win.match(NUM_TOKEN)?.length ?? 0) >= MIN_PIECES) { out += win.replace(NUM_TOKEN, '#'); hit('НОМЕР-КУСКАМИ'); }
    else out += win;
    pos = b;
  }
  return out + text.slice(pos);
}

// ── Наша сторона (владелец 23.10: «убери Монолит и всё, чем менеджер представляется»; имена — пусть
// остаются) ─────────────────────────────────────────────────────────────────────────────────────────
// Название компании и бренды → «[компания]»: «Монолит», «ТД/ТСК Монолит», «ТСК по теплоизоляции», MLT,
// и любое название в представлении менеджера — «компания „X“», «это Александр из Эконом-Строя».

/** Бренды компании в речи и CRM — только падежи названия: «монолитная плита», «монолитное перекрытие» —
 *  строительные термины (их вырезание ломало смысл, 23.10), «Монолитик» — персонаж, не бренд. */
const BRAND = /(?<![а-яёa-z])(?:(?:ТД|ТСК|компани[яиюей]|завод[а-яё]*)\s+)?[«"]?(?:монолит(?:а|у|ом|е)?|mlt|эм[- ]?эл[- ]?ти)[»"]?(?![а-яёa-z])|(?<![а-яё])ТСК(?:\s+по\s+[а-яё]+)?(?![а-яё])/gi;
/** «компания „Эконом-Строй“», «ТД Стройресурс» — название после слова-маркера (с заглавной или в кавычках). */
const INTRO_COMPANY = /(?<![а-яёА-ЯЁ])([Кк]омпани[яиюей]|ТД|[Тт]оргов[а-яё]+ дом[а-яё]*)\s+([«"][^»"\n]{2,40}[»"]|[А-ЯЁA-Z][а-яёa-zA-Z]+(?:[- ][А-ЯЁA-Z]?[а-яёa-zA-Z]+)?)/g;
/** «Александр из Эконом-Строя», «Анастасия с Монолита» — «из/с» + название с заглавной в первых репликах представления. */
const INTRO_FROM = /(?<=(?:это|меня зовут|зовут)\s+[А-ЯЁ][а-яё]+\s+)(?:из|с|со)\s+[«"]?[А-ЯЁA-Z][а-яёa-zA-Z]+(?:[- ][А-ЯЁA-Z]?[а-яёa-zA-Z]+)?[»"]?/g;

export function maskCompany(text: string, hits?: Record<string, number>): string {
  const hit = () => { if (hits) hits['КОМПАНИЯ'] = (hits['КОМПАНИЯ'] ?? 0) + 1; };
  return text
    .replace(BRAND, () => { hit(); return '[компания]'; })
    .replace(INTRO_COMPANY, (_m, word: string) => { hit(); return `${word} [компания]`; })
    .replace(INTRO_FROM, m => { hit(); return `${m.split(/\s+/)[0]} [компания]`; });
}
