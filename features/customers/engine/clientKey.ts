// Единая формула ключа заказчика — задача 2776 (фикс химеры «k0»), разбор:
// owners-inbox/customers-k0-merge-issue.md (задача #2772, Софья).
//
// БЫЛО (везде дублировался один и тот же инлайн CASE):
//   funnel_id IN (0,2) (физ) → 'c'||contact_id
//   funnel_id IN (1,3) (юр)  → 'k'||company_id
// Компания в Битриксе для сделки не привязана ЧАСТО (company_id=0, НЕ NULL) —
// 7 280 сделок / 585 разных реальных контактов схлопывались в ОДНОГО клиента
// 'k0' (247+ млрд ₽, 89 менеджеров, категория «Ключевой» с превышением порога
// в 72 раза). У 99,7% таких сделок при этом есть привязанный contact_id.
//
// СТАЛО (Вариант А отчёта): для funnel 1/3 с company_id=0 — фолбэк на
// contact_id, ПОД ОТДЕЛЬНЫМ префиксом 'x' (не 'c'!) — иначе юр-сделка без
// карточки компании склеилась бы с личной B2C-историей ТОГО ЖЕ контакта
// (если она есть) под одним 'c'-ключом, что было бы новой, другой склейкой.
// 'x'-ключ помечается clientType='contact' (см. deriveClientType ниже) — это
// осознанное отклонение от буквального текста отчёта («сохраняя тип «юр»,
// например 'k0c'||contact_id»): реальная резолвящаяся в Bitrix сущность —
// контакт (crm.contact.list), а не компания; ссылка на несуществующую
// компанию с ID=contact_id была бы хуже, чем честно показать как контакт
// (см. lib/bitrix/clientNames.ts — 'x' роутится в contact-резолвинг).
//
// СОЗНАТЕЛЬНО ВНЕ СКОУПА этого фикса (см. отчёт, п.1.1 и п.1.3 — отдельные,
// соседние проблемы):
//   - company_id IS NULL (не =0) — ~9 677 сделок, «пропуск», не «склейка» —
//     остаются исключены из клиентских движков, как и раньше;
//   - contact_id=0 у физлиц ('c0', зеркальная проблема, 47 сделок) — НЕ
//     трогаем в этой формуле (осталась как была); features/badges/engine/
//     categoryBadges.ts у себя ДОПОЛНИТЕЛЬНО гасит 'c0' отдельным условием —
//     это её собственная, более старая защита, оставлена как есть.
export const CLIENT_KEY_CASE_SQL = `
    CASE
      WHEN d.funnel_id IN (0,2) THEN 'c'||d.contact_id
      WHEN d.company_id = 0 AND d.contact_id IS NOT NULL AND d.contact_id <> 0 THEN 'x'||d.contact_id
      WHEN d.company_id <> 0 THEN 'k'||d.company_id
      ELSE NULL
    END
`;

/** 'k' → компания (реальная, company_id≠0); 'c' и 'x' → резолвятся как контакт
 *  в Bitrix (crm.contact.list) — 'x' семантически юр-сделка без карточки
 *  компании, но физически это контакт, поэтому и ссылка, и имя берутся как
 *  у контакта (см. шапку файла). */
export function deriveClientType(clientKey: string): 'contact' | 'company' {
  return clientKey.startsWith('k') ? 'company' : 'contact';
}
