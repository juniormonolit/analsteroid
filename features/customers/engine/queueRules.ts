/** Окно повторной продажи: столько дней после отгрузки имеет смысл дожимать. */
export const REPEAT_WINDOW_DAYS = 22;

/** Правило владельца 21.09: три касания в окне, по одному на каждой неделе.
 *  Обоснование — исследование «Звонок в первые 22 дня и вторая отгрузка»:
 *  при РАВНОМ числе звонков разнесение по неделям даёт +5,3 п.п. ППО, а звонки
 *  сверх трёх почти не добавляют. Одного звонка мало — до этой правки первый же
 *  звонок закрывал окно, и экран учил ровно обратному новому правилу. */
export const TOUCH_TARGET = 3;
export const TOUCH_WEEK_DAYS = 7;

export type CustomerQueue = 'window' | 'missed' | 'faded' | 'rest';

// Порядок = приоритет звонка слева направо (правка владельца 21.09). «Затихшие
// постоянники» подняты выше «упущенных»: у них 2+ покупок, а значит шанс на
// следующую отгрузку 39–88 % против 19–27 % у разового с упущенным окном.
export const QUEUE_ORDER: CustomerQueue[] = ['window', 'faded', 'missed', 'rest'];
