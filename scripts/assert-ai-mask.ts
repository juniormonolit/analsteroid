// Проверки обезличивания расшифровок перед отправкой в LLM (features/ai-analysis/engine/mask.ts).
// Все примеры синтетические. Запуск: npm run test:ai-mask
import assert from 'node:assert/strict';
import { maskCompany, maskPii } from '../features/ai-analysis/engine/mask.ts';

const masked = (s: string) => maskPii(s).text;
const gone = (s: string, needle: string, msg: string) => assert.ok(!masked(s).includes(needle), `${msg}: «${masked(s)}»`);
const kept = (s: string, needle: string, msg: string) => assert.ok(masked(s).includes(needle), `${msg}: «${masked(s)}»`);

// ── Телефоны ──
gone('Звоните +7 (921) 123-45-67, я на связи', '123-45-67', '+7 со скобками');
gone('мой номер 89211234567', '89211234567', '8 слитно');
gone('Номер 8 911 123 45 67 запиши', '123 45 67', '8 с пробелами');
gone('напишите в Макс 921-123-45-67', '123-45-67', 'без восьмёрки');
gone('К этому номеру привязан Макс? 8-911-***-**-67?', '8-911', 'частично скрыт распознавателем');
gone('Записывай номер. — Сейчас. Девятьсот пять-угу. Пятьдесят семь-шестьдесят. — А как зовут?', 'Пятьдесят семь', 'продиктован кусками словами');
gone('Ну, 905 там 123 45, да, это банк.', '123 45', 'продиктован кусками цифрами');
gone('восемь девятьсот одиннадцать сто двадцать три сорок пять шестьдесят семь', 'сорок пять', 'номер словами подряд');

// ── Карты, ИНН, email ──
gone('Переведи на карту 2200 1234 5678 9012', '5678', 'карта группами');
gone('ИНН 7801234567, выставляйте счёт', '7801234567', 'ИНН юрлица');
gone('пришлите на ivanov.stroy@mail.ru', 'ivanov.stroy', 'email');

// ── Адреса ──
gone('Везите на улица Ленина, дом 15, кв. 3', 'Ленина', 'улица с домом');
gone('Доставка: проспект Просвещения 87 корп 2', 'Просвещения', 'проспект с корпусом');
kept('Объект в посёлке Каменный Мыс, Приозерский район', 'Каменный Мыс', 'посёлок остаётся');

// ── Не трогаем полезное ──
kept('### 2026-04-29T13:45 | сделка 185153 | outbound | 403 с', '2026-04-29', 'дата в заголовке звонка');
kept('сделка 185153', '185153', 'номер сделки (6 цифр)');
kept('Газобетон D400 400х250х625, 44 куба по 5350 рублей', '400х250х625', 'размеры');
kept('Итого 235 400 рублей за кровлю', '235 400', 'сумма');
kept('Если ты деньги на счёт переведёшь 22 400, я верну', '22 400', 'сумма после триггера (две группы)');
kept('Станислав, добрый день, это Елизавета из Монолита', 'Станислав', 'имена остаются');

// ── Счётчик ──
const r = maskPii('Звоните +7 921 123-45-67 или 8 911 765 43 21');
assert.equal(r.hits['ТЕЛЕФОН'], 2, `два телефона: ${JSON.stringify(r.hits)}`);

// ── Наша сторона: бренды и то, чем менеджер представляется (имена остаются) ──
const co = (s: string) => maskCompany(s);
for (const s of ['Здравствуйте, компания «Монолит», Елизавета', 'ТД Монолит, менеджер', 'это ТСК по теплоизоляции', 'Монолита склад', 'MLT доставка']) {
  assert.ok(!/монолит|mlt|тск/i.test(co(s)), `бренд: «${co(s)}»`);
}
assert.ok(!/Эконом/.test(co('Добрый день, это Александр из Эконом-Строя, по заявке')), co('это Александр из Эконом-Строя'));
assert.ok(!/Стройресурс/.test(co('Компания «Стройресурс», Анастасия, здравствуйте')), co('Компания «Стройресурс», Анастасия'));
assert.ok(co('это Александр из Эконом-Строя').includes('Александр'), 'имя менеджера остаётся');
assert.ok(co('Монолитик проверяет').includes('Монолитик'), 'персонаж — не бренд');
for (const s of ['для монолитной плиты М350', 'Монолитное перекрытие?', 'монолитный каркас']) assert.ok(/монолитн/i.test(co(s)), `стройтермин: «${co(s)}»`);
assert.ok(!/Монолит/.test(co('приезжайте в Монолит, оплатите Монолиту, работаем с Монолитом')), 'падежи бренда');
assert.ok(co('я сам из Петербурга, привезите в Парголово').includes('Петербурга'), 'город — не компания');

console.log('ai-mask: ok');
