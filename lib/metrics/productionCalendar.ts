// Производственный календарь РФ (задача 30.07, владелец: «берёшь рабочий
// календарь этого года и предыдущего, смотришь, в какие дни работали и в какие
// нет»). Данные захардкожены — без внешних API: состав нерабочих дней на год
// фиксируется постановлением Правительства РФ осенью предыдущего года и после
// этого не меняется.
//
// ┌────────────────────────────────────────────────────────────────────────┐
// │ ВНИМАНИЕ: календарь надо ПОПОЛНЯТЬ ЕЖЕГОДНО — в конце года добавить    │
// │ запись за следующий год в EXTRA_NON_WORKING (и WORKING_WEEKENDS, если  │
// │ есть перенесённые рабочие субботы). Для года, которого здесь нет,      │
// │ логика автоматически откатывается к наивной «сб/вс = выходной».        │
// └────────────────────────────────────────────────────────────────────────┘
//
// Семантика:
//  * рабочий день = будний (Пн-Пт), НЕ входящий в EXTRA_NON_WORKING, ЛИБО
//    сб/вс из WORKING_WEEKENDS (перенесённая рабочая суббота);
//  * «выходной» = всё остальное (сб/вс + праздники + перенесённые выходные).
//
// Источники: производственные календари РФ.
//  2025 — постановление Правительства РФ № 1335 от 04.10.2024 (переносы:
//    сб 04.01→пт 02.05, вс 05.01→ср 31.12, вс 23.02→чт 08.05, сб 08.03→пт 13.06,
//    сб 01.11→пн 03.11 — поэтому 01.11.2025 РАБОЧАЯ суббота).
//  2026 — постановление № 1466 от 26.09.2025 (переносы: сб 03.01→пт 09.01,
//    вс 04.01→чт 31.12) + автоматические переносы по ст. 112 ТК РФ
//    (вс 08.03→пн 09.03, сб 09.05→пн 11.05). Рабочих суббот в 2026 нет.

// Нерабочие дни, ВКЛЮЧАЯ приходящиеся на сб/вс (для полноты справочника;
// на классификацию влияют только будние даты — сб/вс нерабочие и так).
const EXTRA_NON_WORKING: Record<number, string[]> = {
  2025: [
    '01-01', '01-02', '01-03', '01-04', '01-05', '01-06', '01-07', '01-08', // новогодние каникулы
    '02-23',                   // День защитника Отечества (вс)
    '03-08',                   // 8 Марта (сб)
    '05-01', '05-02',          // Праздник Весны и Труда + перенос с 04.01
    '05-08', '05-09',          // перенос с 23.02 + День Победы
    '06-12', '06-13',          // День России + перенос с 08.03
    '11-03', '11-04',          // перенос с 01.11 + День народного единства
    '12-31',                   // перенос с 05.01
  ],
  2026: [
    '01-01', '01-02', '01-03', '01-04', '01-05', '01-06', '01-07', '01-08', // новогодние каникулы
    '01-09',                   // перенос с сб 03.01
    '02-23',                   // День защитника Отечества (пн)
    '03-08', '03-09',          // 8 Марта (вс) + автоперенос на пн
    '05-01',                   // Праздник Весны и Труда (пт)
    '05-09', '05-11',          // День Победы (сб) + автоперенос на пн
    '06-12',                   // День России (пт)
    '11-04',                   // День народного единства (ср)
    '12-31',                   // перенос с вс 04.01
  ],
  // 2027: [...],  ← добавить по выходу постановления (осень 2026)
};

// Перенесённые РАБОЧИЕ субботы/воскресенья («в какие дни работали»).
const WORKING_WEEKENDS: Record<number, string[]> = {
  2025: ['11-01'], // сб 01.11.2025 — рабочая (перенос на пн 03.11)
  2026: [],
};

function toDates(map: Record<number, string[]>): string[] {
  return Object.entries(map).flatMap(([y, days]) => days.map(d => `${y}-${d}`));
}

/** SQL-литерал date[] всех «дополнительных нерабочих» дат справочника. */
function nonWorkingArraySql(): string {
  return `ARRAY[${toDates(EXTRA_NON_WORKING).map(d => `'${d}'`).join(',')}]::date[]`;
}

/** SQL-литерал date[] рабочих суббот/воскресений (может быть пустым). */
function workingWeekendArraySql(): string {
  const dates = toDates(WORKING_WEEKENDS);
  return dates.length ? `ARRAY[${dates.map(d => `'${d}'`).join(',')}]::date[]` : `ARRAY[]::date[]`;
}

/**
 * SQL-предикат «дата — рабочий день по производственному календарю».
 * `dateExpr` — выражение типа date (уже в нужном часовом поясе!). Даты —
 * константы из справочника выше (не пользовательский ввод), инлайн безопасен.
 */
export function isWorkingDaySql(dateExpr: string): string {
  return `((EXTRACT(ISODOW FROM ${dateExpr}) BETWEEN 1 AND 5 AND NOT (${dateExpr}) = ANY(${nonWorkingArraySql()}))
    OR (${dateExpr}) = ANY(${workingWeekendArraySql()}))`;
}

/** JS-версия того же предиката (для тестов/клиентских проверок). date — локальная МСК-дата. */
export function isWorkingDayJs(year: number, month1: number, day: number, isoDow: number): boolean {
  const key = `${String(month1).padStart(2, '0')}-${String(day).padStart(2, '0')}`;
  if ((WORKING_WEEKENDS[year] ?? []).includes(key)) return true;
  if (isoDow > 5) return false;
  return !(EXTRA_NON_WORKING[year] ?? []).includes(key);
}
