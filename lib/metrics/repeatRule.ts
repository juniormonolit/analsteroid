// ── Правило повторной продажи (решение владельца 21.09.2026) ─────────────────
//
// ЗАЧЕМ. Одна продажа часто разбивается в Битриксе на несколько сделок: тысяча
// кубов песка уезжает десятью машинами по сто, и в базе это десять отгрузок.
// Любой счёт повторных продаж без поправки завышает и число покупок, и долю
// вернувшихся, и вероятность повтора.
//
// ПРАВИЛО. Отгрузка (или продажа) считается НОВОЙ, если выполняется хотя бы одно:
//   а) другая головная товарная группа («по наибольшему», head_group_name);
//   б) с предыдущей прошло 7 дней и больше.
// Иначе она приклеивается к предыдущей покупке: деньги суммируются, покупка
// остаётся одна.
//
// ОКНО СКОЛЬЗЯЩЕЕ — отсчитывается от ПРЕДЫДУЩЕЙ отгрузки, а не от первой в
// серии. Длинный отгруз партиями раз в три-четыре дня схлопывается цепочкой
// целиком; при отсчёте от первой он рвался бы на седьмой день.
//
// МАСШТАБ (замер 21.09.2026, вся история): склеивается 1 757 отгрузок из
// 31 876 (5,5 %). Доля заказчиков, дошедших до второй покупки, падает с 21,1 %
// до 18,8 % — то есть каждый девятый «повторный» заказчик был дроблением.
// Вероятность следующей отгрузки проседает на 0,7–2,3 п.п. по всем сегментам.
//
// ПРО АДРЕС (проверено и ОТКЛОНЕНО как обязательное условие). Гипотеза была,
// что совпадение адреса объекта делает склейку почти достоверной. Замер по
// deal_addresses (system-БД, координаты у 81 % отгрузок): среди пар «тот же
// материал, разрыв < 7 дней» объекты совпадают в 90 % случаев, но среди пар
// «другой материал» или «разрыв 30+ дней» — в 80–84 %. То есть заказчик и так
// почти всегда возит на один объект: адрес подтверждает склейку, но почти не
// РАЗЛИЧАЕТ её от обычного повтора (прибавка ~6–10 п.п., а не 99,9 %).
// Как вето («не склеивать, если объекты дальше 10 км») он снимает лишь 2,4 %
// склеек, причём координаты известны у обоих участников только в половине пар,
// а таблица адресов лежит в ДРУГОЙ базе — кросс-базный джойн ради 2,4 % в
// продовых путях не окупается. Поэтому адрес в правило не входит; для разовых
// исследований вето можно включить руками (см. WORKLOG 21.09).

/** Разрыв, с которого отгрузка считается новой покупкой, дней. */
export const REPEAT_SPLIT_GAP_DAYS = 7;

/**
 * SQL-предикат «эта строка начинает НОВУЮ покупку».
 * Ожидает, что в области видимости уже есть колонки предыдущей строки окна:
 * `prevAt`/`prevGroup` (обычно через `lag(...) OVER (PARTITION BY клиент ORDER BY дата, id)`).
 *
 * @param at       колонка даты текущей строки (delivered_at / sold_at)
 * @param group    колонка головной товарной группы текущей строки
 * @param prevAt   та же дата предыдущей строки окна
 * @param prevGroup та же группа предыдущей строки окна
 */
export function isNewPurchaseSql(at: string, group: string, prevAt: string, prevGroup: string): string {
  return `CASE
    WHEN ${prevAt} IS NULL THEN 1
    WHEN ${group} IS DISTINCT FROM ${prevGroup} THEN 1
    WHEN ${at} >= ${prevAt} + interval '${REPEAT_SPLIT_GAP_DAYS} days' THEN 1
    ELSE 0 END`;
}

/**
 * Готовый кусок SQL: из таблицы отгрузок делает таблицу ПОКУПОК.
 * `src` должен отдавать колонки client_key, deal_id, at, amount, grp (+ любые
 * другие, которые нужны — они не переносятся, берите их отдельно).
 * Результат: client_key, pno (номер покупки), at (первая отгрузка покупки),
 * amount (сумма всех частей), grp, parts (из скольких отгрузок склеена).
 */
export function mergedPurchasesSql(src: string): string {
  return `
    SELECT client_key, pno, min(at) AS at, sum(amount) AS amount, min(grp) AS grp, count(*)::int AS parts
    FROM (
      SELECT *, sum(is_new) OVER (PARTITION BY client_key ORDER BY at, deal_id ROWS UNBOUNDED PRECEDING) AS pno
      FROM (
        SELECT s.*, ${isNewPurchaseSql('s.at', 's.grp', 'lag(s.at) OVER w', 'lag(s.grp) OVER w')} AS is_new
        FROM (${src}) s
        WINDOW w AS (PARTITION BY s.client_key ORDER BY s.at, s.deal_id)
      ) f
    ) z
    GROUP BY client_key, pno`;
}
