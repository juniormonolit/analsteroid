// Сервисные товарные группы — то, что НЕ считается покупкой категории.
//
// Решение владельца 10.08.2026: «не считать товарную группу "Услуги", упаковку,
// доставку и всякое такое. Если в сделке есть "газобетон" и "доставка" — это
// сделка по "Газобетону" и в ней всего 1 товарная группа». Утверждённый им
// список — ровно пять head-групп ниже.
//
// ПОЧЕМУ ПО ID, А НЕ ПО ИМЕНИ: имя группы редактируется в Битриксе, id — нет.
// Переименуют «Перевозку» в «Логистику» — метрики молча начнут считать доставку
// покупкой, и заметит это никто. Имена держим в комментарии для читаемости.
//
// ПОЧЕМУ НЕ ПО `type` ПОЗИЦИИ: в products есть type='услуга' (17 486 позиций),
// но «Доставка без разгрузки» лежит там с type='товар' — по типу отфильтровать
// не получится, режем именно по группе.
//
// ПОЧЕМУ НЕ ПО `deals.head_group_name`: это ОДНА главная группа сделки (по
// наибольшей сумме). На проде 473 отгрузки с реальным товаром имеют главную
// группу «Перевозка» — доставка вышла дороже товара. Считать по ней значило бы
// выкинуть эти сделки целиком. Поэтому все группы сделки берутся из позиций
// (`products`), а главная группа для этих метрик не используется вовсе.
export const SERVICE_HEAD_GROUP_IDS = [
  95,  // Аренда спецтехники
  101, // Для логистов
  181, // Перевозка
  344, // Служебная
  571, // Ошибка
] as const;

/** SQL-условие «позиция products с алиасом `alias` — товарная, а не сервисная».
 *  Позиция без группы (head_group_id IS NULL) товарной НЕ считается: приписать её
 *  к категории всё равно невозможно, а «покупка категории» — это и есть предмет
 *  всех метрик раздела «Клиенты». */
export function goodsPositionWhere(alias: string): string {
  return `(${alias}->>'head_group_id') IS NOT NULL
      AND (${alias}->>'head_group_id')::bigint NOT IN (${SERVICE_HEAD_GROUP_IDS.join(', ')})`;
}

/** SQL-условие «в сделке с алиасом `dealAlias` есть хотя бы одна товарная позиция». */
export function dealHasGoodsWhere(dealAlias: string): string {
  return `EXISTS (
      SELECT 1 FROM jsonb_array_elements(${dealAlias}.products) _gp
       WHERE ${goodsPositionWhere('_gp')}
    )`;
}
