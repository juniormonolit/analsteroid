// Календарная дата по Москве (ГГГГ-ММ-ДД) для границы периода: UI шлёт границы
// МСК-суток как ISO (00:00 и 23:59:59.999 МСК), API «Реализации» принимает даты.
// Без зависимостей — используется и в браузере, и в движке отчёта (задача #8126).
export function mskYmd(d: Date): string {
  return new Date(d.getTime() + 3 * 3600_000).toISOString().slice(0, 10);
}
