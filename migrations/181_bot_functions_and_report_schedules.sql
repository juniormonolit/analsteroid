-- ── Расписания авторассылки сохранённых отчётов ─────────────────────────────
CREATE TABLE IF NOT EXISTS report_schedules (
  id                 uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  template_id        uuid NOT NULL REFERENCES report_templates(id) ON DELETE CASCADE,
  -- Чьими глазами собирать отчёт: владелец шаблона (его доступ к отделам/филиалам,
  -- его «я» в сущности self). Дублируем из report_templates, чтобы не терять при
  -- переименовании и не джойнить на каждом тике.
  owner_login        text NOT NULL,
  recipient_bitrix_id text NOT NULL,
  send_time          time NOT NULL DEFAULT '18:00',
  -- Дни недели ISO: 1 = понедельник … 7 = воскресенье.
  weekdays           int[] NOT NULL DEFAULT '{1,2,3,4,5}',
  enabled            boolean NOT NULL DEFAULT false,
  created_by         text,
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now(),
  last_sent_at       timestamptz,
  last_error         text,
  CHECK (array_length(weekdays, 1) >= 1)
);
CREATE INDEX IF NOT EXISTS report_schedules_enabled_idx ON report_schedules (enabled, send_time);
COMMENT ON TABLE report_schedules IS
  'Авторассылка сохранённых шаблонов «Мой отчёт» ботом «Аналитик» (задача 09.09.2026). Срабатывает при включённой функции report_schedules И enabled расписания; раннер — lib/jobs/reportSchedules.ts, тик раз в минуту по МСК.';
