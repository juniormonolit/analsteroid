-- правка владельца 02.08). Дословно: «надо чтобы менеджер понимал — общение с
-- аналитиком это его личка. И возможно стоит дать менеджеру в ЛК ещё и власть
-- над ним. Вкл/выкл полностью, только ежедневный дайджест или только
-- еженедельный. Подсказывать только по заказчикам или ещё и по цифрам».
--
-- Отсутствие строки = все включено (дефолт для новых сотрудников, из брифа).
-- ТРИ принципиальных правила владельца, соблюдены в коде (не в схеме):
--  1. Настройки видны только самому менеджеру + роли с правом
--     action.subscriptions.view_all (директор и выше, только просмотр,
--     БЕЗ права менять чужое) — см. lib/auth/perms.ts, PERM_ACTIONS.
--     РОП это право НЕ получает по умолчанию (и не должен — «не должен видеть,
--     кто что отключил»).
--  2. Финансовые уведомления (переводы/начисления/выплаты/сгорание валюты)
--     НЕ управляются этой таблицей вообще — они вне периметра дайджеста/
--     подсказок и всегда идут своим путём (payout/transfer/gift/expiry —
--     существующие pushViaAnalitik-вызовы, не тронуты этой задачей).
--  3. Отключение не наказывается — таблица не участвует ни в одном расчёте
--     наград/рейтинга/XP, только в гейте отправки дайджеста/подсказок.
--
-- DOWN:
--   DROP TABLE IF EXISTS manager_bot_prefs;
--   ALTER TABLE bot_outbound_log DROP COLUMN IF EXISTS suppress_reason;

CREATE TABLE IF NOT EXISTS manager_bot_prefs (
  bitrix_id         integer PRIMARY KEY,
  enabled           boolean NOT NULL DEFAULT true,  -- главный тумблер «получать сообщения от Аналитика»
  daily_digest      boolean NOT NULL DEFAULT true,
  weekly_digest     boolean NOT NULL DEFAULT true,
  advice_customers  boolean NOT NULL DEFAULT true,   -- подсказки по заказчикам (+ их фидбек-цикл)
  advice_numbers    boolean NOT NULL DEFAULT true,   -- гамбургер цифр/трендов в дайджесте
  updated_at        timestamptz NOT NULL DEFAULT now()
);

-- Различаем в логе, был ли пуш подавлен глобальным dry-run или личной
-- настройкой получателя (владелец просил «в лог пишем с пометкой, что
-- человек отписан и в бою сообщение бы не ушло» — отдельно от dry-run).
ALTER TABLE bot_outbound_log ADD COLUMN IF NOT EXISTS suppress_reason text;
