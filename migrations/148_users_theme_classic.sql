-- Четвёртая тема «Классическая» + смена значения по умолчанию (решение владельца,
-- 04.08). Контекст: редизайн «Монолитика Glass» (задача 2999) выехал на прод как
-- безальтернативный — прежнего плоского вида в приложении не осталось. Владелец
-- попросил вернуть его отдельной темой и сделать ДЕФОЛТОМ для всех, а стекло оставить
-- опцией: «По умолчанию у всех должна быть классическая. Кто захочет — перетавит».
--
-- Что делает миграция:
--   1) расширяет CHECK до четырёх значений ('classic','light','dark','mono');
--   2) меняет DEFAULT колонки на 'classic' (новые пользователи и приглашённые
--      менеджеры из Битрикса получают плоский вид);
--   3) переводит на 'classic' ВСЕХ, у кого сейчас 'light'.
--
-- Почему безопасно тронуть существующие строки (обычно так делать нельзя): 'light'
-- у всех 33 пользователей — это НЕ их выбор, а прежний DEFAULT колонки (миграция 070).
-- Осознанный выбор темы до сегодняшнего дня мог быть только 'dark' или 'mono' — их
-- НЕ трогаем, эти люди тему переключали руками.
--
-- ВАЖНО, почему CHECK переписывается заново, а не «просто добавляется значение»:
-- миграция 145 (третье значение 'mono') на этот контур НЕ накатилась — проверено
-- живьём 04.08: pg_constraint показывал users_theme_check = CHECK (theme IN
-- ('light','dark')), а UPDATE users SET theme='mono' отбивался констрейнтом. Отсюда и
-- жалоба владельца «Серое стекло так и не накатилось: в настройках не применяется, на
-- секунду моргает серым и откатывается на предыдущую» — оптимистичный applyTheme()
-- красил экран, PATCH /api/me/theme падал 500 на CHECK, refetch возвращал старое
-- значение, useEffect перекрашивал обратно. Эта миграция идемпотентно ставит
-- ограничение в актуальный вид независимо от того, доехала 145 или нет.
--
-- БД: YC system.

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'users_theme_check') THEN
    ALTER TABLE users DROP CONSTRAINT users_theme_check;
  END IF;

  ALTER TABLE users
    ADD CONSTRAINT users_theme_check
    CHECK (theme IN ('classic', 'light', 'dark', 'mono'));
END $$;

ALTER TABLE users ALTER COLUMN theme SET DEFAULT 'classic';

UPDATE users SET theme = 'classic' WHERE theme = 'light' OR theme IS NULL;

COMMENT ON COLUMN users.theme IS
  'Тема оформления: classic (плоский вид до редизайна, дефолт), light/dark/mono — стеклянные темы «Монолитика Glass» (в интерфейсе: Светлое/Синее/Серое стекло).';
