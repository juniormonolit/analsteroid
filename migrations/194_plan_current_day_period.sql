-- Миграция 194: «План (на текущий день)» и его % — от ВЫБРАННОГО ПЕРИОДА
-- БД: YC ANALYTICS (каталог метрик). Накат:
--   node migrations/run_local.mjs migrations/194_plan_current_day_period.sql --db=analytics
--
-- Правка владельца 31.08 (п.8): «Метрика "План отгрузок (на текущий день)"
-- игнорирует выбранный период. По задумке там должен быть план отгрузок на день
-- × кол-во рабочих дней в периоде» (и продажная — так же).
--
-- Серверная часть уже переопределена (app/api/reports/run/route.ts, workdaysOf):
-- plan_*_current_day = дневной план (месячный ÷ 20) × рабочие дни ВЫБРАННОГО
-- периода по working_calendar (окно обрезается сегодняшним днём; период целиком
-- в будущем → 0). Раньше окно было жёстко [начало текущего месяца, сегодня].
--
-- Эта миграция чинит СОГЛАСОВАННОСТЬ процентов выполнения: их числителем был
-- факт С НАЧАЛА МЕСЯЦА (sales_fact_month) — с периодным знаменателем это дало бы
-- «неделя ÷ месяц». Теперь числитель — факт ЗА ПЕРИОД строки (перв.+повт.
-- продажи/отгрузки — collected-метрики, есть в каждой строке всегда).

UPDATE metrics SET
  formula = '([primary_sales_amount] + [repeat_sales_amount]) / [plan_sales_current_day] * 100',
  dependencies = ARRAY['primary_sales_amount', 'repeat_sales_amount', 'plan_sales_current_day'],
  description = 'Факт продаж (перв.+повт.) ЗА ВЫБРАННЫЙ ПЕРИОД ÷ план на текущий день (дневной план = месячный ÷ 20, × кол-во рабочих дней периода по производственному календарю; окно обрезается сегодняшним днём). До 31.08 сравнивал факт с начала месяца с планом по прошедшим рабочим дням месяца и не реагировал на период отчёта.',
  formula_human = 'сумма продаж (первичные + повторные) за период ÷ (месячный план продаж ÷ 20 × рабочие дни периода) × 100'
WHERE id = 'plan_exec_pct_sales_current_day';

UPDATE metrics SET
  formula = '([primary_shipments_amount] + [repeat_shipments_amount]) / [plan_shipments_current_day] * 100',
  dependencies = ARRAY['primary_shipments_amount', 'repeat_shipments_amount', 'plan_shipments_current_day'],
  description = 'Факт отгрузок (перв.+повт.) ЗА ВЫБРАННЫЙ ПЕРИОД ÷ план отгрузок на текущий день (дневной план = месячный ÷ 20, × кол-во рабочих дней периода по производственному календарю; окно обрезается сегодняшним днём). До 31.08 сравнивал факт с начала месяца с планом по прошедшим рабочим дням месяца и не реагировал на период отчёта.',
  formula_human = 'сумма отгрузок (первичные + повторные) за период ÷ (месячный план отгрузок ÷ 20 × рабочие дни периода) × 100'
WHERE id = 'plan_exec_pct_shipments_current_day';

UPDATE metrics SET
  description = 'Дневной план продаж (месячный ÷ 20) × кол-во рабочих дней ВЫБРАННОГО периода по производственному календарю (working_calendar); окно обрезается сегодняшним днём — будущие дни не считаются. До 31.08 не зависел от периода (всегда прошедшие рабочие дни текущего месяца).',
  formula_human = 'месячный план продаж ÷ 20 × рабочие дни выбранного периода (не позже сегодня)'
WHERE id = 'plan_sales_current_day';

UPDATE metrics SET
  description = 'Дневной план отгрузок (месячный ÷ 20) × кол-во рабочих дней ВЫБРАННОГО периода по производственному календарю (working_calendar); окно обрезается сегодняшним днём — будущие дни не считаются. До 31.08 не зависел от периода (всегда прошедшие рабочие дни текущего месяца).',
  formula_human = 'месячный план отгрузок ÷ 20 × рабочие дни выбранного периода (не позже сегодня)'
WHERE id = 'plan_shipments_current_day';

SELECT id, formula FROM metrics WHERE id IN ('plan_exec_pct_sales_current_day','plan_exec_pct_shipments_current_day');
