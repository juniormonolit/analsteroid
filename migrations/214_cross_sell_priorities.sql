-- 214: ручные приоритеты «что предложить» (правка владельца 21.09).
--
-- Статистика переходов честная, но шумная: после «Газобетон» она советует
-- «Сухие смеси» — клей к блокам берут ТОЙ ЖЕ покупкой, это не допродажа, а
-- сопутствующий товар. Владелец: «может вытащить весь список категорий в
-- настройки и для каждого задавать вручную до 3х приоритетов? Например, после
-- газобетона я бы поставил кровлю, утеплитель, плитные и только потом
-- "по статистике"».
--
-- Ручные приоритеты идут ПЕРВЫМИ в «Предложить» (в заданном порядке), следом —
-- обычный статистический топ-3 без дублей. Настройка per head-группу последней
-- покупки; правит супер-админ в «Настройки → Что предложить».

CREATE TABLE IF NOT EXISTS cross_sell_priorities (
  from_group text PRIMARY KEY,                       -- head_group_name последней покупки
  groups     text[] NOT NULL                         -- до 3 групп в порядке приоритета
             CHECK (cardinality(groups) BETWEEN 1 AND 3),
  updated_at timestamptz NOT NULL DEFAULT now(),
  updated_by text
);

COMMENT ON TABLE cross_sell_priorities IS
  'Ручные приоритеты кросс-селла: после группы X сначала предлагать эти группы, потом статистику (задача 21.09)';

-- Пример владельца из постановки — заполняем сразу, чтобы было видно, как это
-- работает (правится/сбрасывается в «Настройки → Что предложить»):
-- «после газобетона я бы поставил кровлю, утеплитель, плитные».
INSERT INTO cross_sell_priorities (from_group, groups, updated_by)
VALUES ('Газобетон',
        ARRAY['Кровельные материалы, водосточные системы', 'Теплоизоляция и утеплитель', 'Плитные материалы'],
        'миграция 214')
ON CONFLICT (from_group) DO NOTHING;
