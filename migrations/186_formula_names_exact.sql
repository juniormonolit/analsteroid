-- Migration 186: имена метрик в ручных формулах — точными именами каталога
-- БД: YC analytics (таблица metrics). Накат с ноутбука:
--   node migrations/run_local.mjs migrations/186_formula_names_exact.sql --db=analytics
--
-- Задача владельца 24.08 (продолжение 185): по «имени» в формуле теперь можно
-- провалиться в описание той метрики (MetricInfoBody.tsx). Резолвер сопоставляет
-- текст в «ёлочках» с каталогом по точному имени или его началу с границей
-- слова. Два семейства из 185 ссылались на метрики ПЕРЕСКАЗОМ имени — такие
-- ссылки не резолвятся и остаются мёртвым текстом:
--   * «Вернувшихся за N дней»  → у метрики имя «Вернувшихся клиентов за N дней (счётчик)»;
--   * «Повторные клиенты когорты (2+ заказов)» → имя «Количество повторных клиентов (2+ заказов)».
-- Приводим цитаты к началу настоящих имён — и ссылка живая, и текст человеческий.

BEGIN;

UPDATE metrics SET formula_human =
  '= «Вернувшихся клиентов за ' || w.d || ' дней» ÷ «Клиентов в когорте» × 100. Пусто, пока окно не прожито всей когортой'
  FROM (VALUES ('30'), ('60'), ('90'), ('180'), ('360')) AS w(d)
 WHERE metrics.id = 'cohort_return_rate_' || w.d;

UPDATE metrics SET formula_human =
  '= «Количество повторных клиентов (2+ заказов)» ÷ «Клиентов в когорте» × 100'
 WHERE id = 'cohort_return_rate_total';

COMMIT;
