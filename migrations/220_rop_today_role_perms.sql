-- 220: «РОП — сегодня» (/rop) — выдать право раздела рабочим ролям (баг владельца
-- 28.09: «Юлия Зианбетова не видит свою команду и команду Ухановой»).
--
-- Диагноз: у Юлии всё настроено верно — в «Пользователи → Руководит» ей назначены
-- «Команда Зианбетовой» (14 активных) и «Команда Ухановой» (13). Но страница /rop
-- гейтится правом section.rop_today, а его НЕ БЫЛО НИ У ОДНОЙ роли: ключ появился в
-- каталоге (lib/auth/perms.ts, задача #6446), а в roles.permissions его никто не
-- проставил. Админы проходили только по джокеру section.*. Поэтому РОП/Директор/
-- Пользователь получали «Недостаточно прав» и до ropScope() дело не доходило вовсе.
--
-- Роли: Пользователь / РОП / Директор — по словам владельца («речь только о
-- пользователях, ропах и директорах»); МОП — та же роль менеджера, что и
-- «Пользователь» (сейчас 0 носителей), добавлена, чтобы баг не повторился при
-- переводе людей на неё. Логист остаётся без права: лателеральная функция, не продажи.
UPDATE roles
   SET permissions = (SELECT ARRAY(SELECT DISTINCT unnest(permissions || ARRAY['section.rop_today'])))
 WHERE name IN ('Пользователь', 'РОП', 'Директор', 'МОП')
   AND NOT (permissions @> ARRAY['section.rop_today']);

-- «Естественно админы должны видеть все» (владелец 28.09). Задача #6479 сознательно
-- увела «полный доступ» на /rop с hasFullManagerAccess на ПОФАМИЛЬНОЕ право
-- action.rop_today.full_access (джокер section.* его не покрывает) — иначе всю
-- компанию видели и маркетолог с разработчиком на той же роли. Выдаём это право
-- роли «Администратор» явно: механизм сохраняется, кому не положено — снимается
-- галочкой в «Настройки → Роли» или переводом на другую роль.
UPDATE roles
   SET permissions = (SELECT ARRAY(SELECT DISTINCT unnest(permissions || ARRAY['action.rop_today.full_access'])))
 WHERE name = 'Администратор'
   AND NOT (permissions @> ARRAY['action.rop_today.full_access']);
