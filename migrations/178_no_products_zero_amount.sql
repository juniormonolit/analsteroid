-- 178: «Без товаров» — только сделки с НУЛЕВОЙ суммой (правка владельца 11.08).
-- БД: analytics (metrics).
--
-- Жалоба: «У менеджеров в "Без товаров" отображаются сделки с товаром и ценами.
-- Товары внесены верно, проверял. В "Без товаров" должны отображаться только те
-- сделки, где сумма 0.»
--
-- Что показала проверка (живые данные, сделки с 01.07.2026):
--   без товарных строк, сумма 0     — 4368   ← настоящие «без товаров»
--   без товарных строк, сумма > 0   —  173   ← то, на что жалуется владелец
--   со строками, сумма 0            —  184
--   со строками, сумма > 0          — 18401
-- Две сделки со скриншотов (220665 «Винтовые сваи», 220975 «Аэродромные плиты»)
-- запрошены НАПРЯМУЮ В БИТРИКСЕ через crm.deal.productrows.get: там у каждой по
-- одной товарной строке и сумма 17-20 тыс, а в sa.deals products пуст. То есть
-- владелец прав — товары внесены, до аналитики они не доехали. Настоящая причина
-- не в метрике, а в синхронизации sa.deals (см. WORKLOG 11.08), и она чинится
-- отдельно на стороне выгрузки.
--
-- Почему добавляем условие И-строгим, а не заменяем им товарное:
-- «сумма = 0» ВМЕСТО «нет товарных строк» затащило бы в метрику 184 сделки, где
-- товары как раз заполнены, а сумма нулевая — это другой дефект (товар без цены),
-- и он не про «без товаров». Пересечение двух условий ровно и означает то, что
-- владелец просит показывать: пустая сделка, в которой нет ни товаров, ни денег.
--
-- DOWN:
--   UPDATE metrics SET filters = '[{"field":"products","op":"is_null","value":""}]'::jsonb
--    WHERE id = 'no_products_count';
--   UPDATE metrics SET filters = '[{"field":"funnel_type","op":"eq","value":"primary"},{"field":"products","op":"is_null","value":""}]'::jsonb
--    WHERE id = 'no_products_primary_count';
--   UPDATE metrics SET filters = '[{"field":"funnel_type","op":"eq","value":"repeat"},{"field":"products","op":"is_null","value":""}]'::jsonb
--    WHERE id = 'no_products_repeat_count';

UPDATE metrics SET
  filters = '[{"field":"products","op":"is_null","value":""},{"field":"amount","op":"eq","value":"0"}]'::jsonb,
  description = 'Сделки без товарных строк (products NULL или пустой массив) И с нулевой суммой, созданные за период, все воронки. Условие «сумма 0» добавлено 11.08 по правке владельца: сделки с суммой, но без товарных строк — это дефект выгрузки товаров, а не «без товаров». Задача #2548.'
WHERE id = 'no_products_count';

UPDATE metrics SET
  filters = '[{"field":"funnel_type","op":"eq","value":"primary"},{"field":"products","op":"is_null","value":""},{"field":"amount","op":"eq","value":"0"}]'::jsonb,
  description = 'Сделки без товарных строк И с нулевой суммой, созданные за период, первичные воронки (funnels.is_repeat=false). Условие «сумма 0» — правка владельца 11.08. Задача #2548.'
WHERE id = 'no_products_primary_count';

UPDATE metrics SET
  filters = '[{"field":"funnel_type","op":"eq","value":"repeat"},{"field":"products","op":"is_null","value":""},{"field":"amount","op":"eq","value":"0"}]'::jsonb,
  description = 'Сделки без товарных строк И с нулевой суммой, созданные за период, повторные воронки (funnels.is_repeat=true). Условие «сумма 0» — правка владельца 11.08. Задача #2548.'
WHERE id = 'no_products_repeat_count';
