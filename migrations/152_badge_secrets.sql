-- Ачивки: секретные награды и комплекты (задача владельца 05.08).
--
-- Раздел «Награды» становится коллекцией достижений: редкость (частота
-- встречаемости у коллег) считается на лету из badge_awards, неполученные
-- показываются блеклыми — а СЕКРЕТНЫЕ не показываются вообще, пока не получены
-- («секретки, которых даже блеклыми не отображается»).
--
-- is_secret — флаг скрытности: такой бейдж не попадает в список неполученных.
-- set_of   — комплект: массив ключей других наград; когда собраны ВСЕ, секретка
--            выдаётся сама (движок соберёт её в отдельном проходе). Пусто =
--            обычная награда, выдаётся правилом/руками.
-- Кастомные ачивки «за что угодно» (пример владельца: «Разозлил охранника в БЦ
-- и сумел скрыться») уже возможны — badge_definitions с CUSTOM_PREFIX, создаёт
-- и присваивает только админ.
--
-- СИСТЕМНАЯ БД (YC) — вручную через migrations/run_system.mjs, ОТДЕЛЬНО на dev
-- (junibaseone) и prod (system).
-- DOWN: ALTER TABLE badge_definitions DROP COLUMN is_secret, DROP COLUMN set_of;

ALTER TABLE badge_definitions
  ADD COLUMN IF NOT EXISTS is_secret boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS set_of    text[] NOT NULL DEFAULT '{}';

COMMENT ON COLUMN badge_definitions.is_secret IS
  'Секретная ачивка: не показывается в списке неполученных (даже блеклой), появляется только после получения.';
COMMENT ON COLUMN badge_definitions.set_of IS
  'Комплект: ключи наград, которые нужно собрать целиком. Когда собраны все — ачивка выдаётся автоматически. Пусто = обычная награда.';
