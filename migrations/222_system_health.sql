-- Повод: ночной синк оргструктуры падал с «permission denied for table employees»,
-- и об этом никто не узнал — сообщение ушло в app.log, который никто не читает.
-- Проверки смотрят на НАБЛЮДАЕМЫЕ СЛЕДСТВИЯ (свежесть данных), а не на факт запуска
-- джобы: если джоба умерла, данные протухнут и это увидят, даже когда сама джоба
-- молчит. Состояние храним, чтобы (а) писать о ПОЯВИВШЕЙСЯ поломке сразу, а не ждать
-- утра, и (б) не слать одно и то же каждые 10 минут.
CREATE TABLE IF NOT EXISTS system_health_state (
  key           TEXT PRIMARY KEY,
  ok            BOOLEAN NOT NULL,
  detail        TEXT,
  checked_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  -- когда поломка началась (NULL, пока всё хорошо) — чтобы в сводке писать «с 03:12»
  failed_since  TIMESTAMPTZ,
  -- когда последний раз писали владельцу про ЭТУ поломку (антиспам)
  last_alert_at TIMESTAMPTZ
);

