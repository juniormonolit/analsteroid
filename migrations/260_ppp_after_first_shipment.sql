-- БД: analytics (таблица metrics). Накат с прода (локальный контейнер, YC мёртв с 08.10):
--   ssh … docker exec -i analsteroid-sys-pg psql -U $POSTGRES_USER -d analytics -1 < migrations/260_ppp_after_first_shipment.sql
--
-- Владелец 29.10: «ППП — это вторая ПРОДАЖА после первичной отгрузки. Не после продажи».
-- Сам расчёт — в коде (pppSubquery в lib/metrics/sqlGen.ts), фильтр _ppp у ppp_count /
-- ppp_amount не меняется. Здесь только описания, чтобы подсказки «i» не врали.
-- Порядок с кодом не важен. Накат безопасен повторно.

UPDATE metrics SET
  description = 'ППП: сделки периода (sold_at), которые стали ПЕРВОЙ продажей заказчика (contact_id) после его первой отгрузки (min delivered_at по всей истории). Продажи, потом ушедшие в отказ, и довоз считаются. До 29.10.2026 — вторая продажа по истории (rn=2 по sold_at).',
  human_description = 'Сколько заказчиков вернулись за второй покупкой. 1) Находим первую отгрузку заказчика за всю историю. 2) Первая продажа после неё — это ППП. 3) Считаем ППП, чья дата продажи попала в период.'
WHERE id = 'ppp_count';

UPDATE metrics SET
  description = 'Сумма ППП: сделки периода (sold_at), которые стали ПЕРВОЙ продажей заказчика (contact_id) после его первой отгрузки. До 29.10.2026 — вторая продажа по истории.',
  human_description = 'Сумма сделок ППП — первых продаж заказчиков после их первой отгрузки, проданных в периоде.'
WHERE id = 'ppp_amount';

UPDATE metrics SET
  description = 'Конверсия ППП: ППП периода (первая продажа заказчика после его первой отгрузки) / первичные отгрузки периода (по воронке) × 100.',
  human_description = 'Какая доля первичных отгрузок оборачивается следующей продажей: ППП ÷ первичные отгрузки периода.'
WHERE id = 'ppp_conversion';

SELECT id, left(description, 70) FROM metrics WHERE id IN ('ppp_count', 'ppp_amount', 'ppp_conversion');
