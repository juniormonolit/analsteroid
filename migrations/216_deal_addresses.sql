-- 216: адреса объектов сделок из Битрикса (задача владельца 21.09).
--
-- Адрес ведут ТОЛЬКО на сделке, в поле UF_ADDRESS_COORDS (проверено 21.09:
-- 489 из 500 последних закрытых сделок, 98%); формат
-- «155020, Ивановская обл, ... поселок Петровский||56.645326,40.317863» —
-- до «||» адрес, после — широта,долгота (иногда только город без координат).
-- В sa.deals адреса нет и синк его не тянет, у компаний/контактов адресные
-- поля пустые. Поэтому — свой кэш: заполняется лениво при открытии карточки
-- сделки/заказчика и целиком фоновым бэкфиллом (ID-пагинация батчами 50×50,
-- вся база 254 тыс. сделок проходится за считанные минуты).
--
-- Адрес нужен трём вещам: строка «объект» в карточке сделки и в списке сделок
-- заказчика, признак «строит на нескольких объектах» у заказчика и спец-отчёт
-- на карте.

CREATE TABLE IF NOT EXISTS deal_addresses (
  deal_id    bigint PRIMARY KEY,
  address    text,                                  -- человекочитаемая часть (до «||»)
  lat        double precision,                      -- широта, NULL если координат не было
  lon        double precision,
  raw        text,                                  -- как пришло из Битрикса (на случай разбора формата заново)
  region_id  text,                                  -- UF_REGION (филиал), справочник в Битриксе
  fetched_at timestamptz NOT NULL DEFAULT now(),    -- когда последний раз спрашивали Битрикс
  found      boolean NOT NULL DEFAULT true          -- false = спрашивали, адреса нет (не дёргать Битрикс на каждый показ)
);

-- Точки для карты: только заполненные координаты.
CREATE INDEX IF NOT EXISTS deal_addresses_coords_idx ON deal_addresses (lat, lon) WHERE lat IS NOT NULL;
-- Бэкфилл идёт по возрастанию deal_id; индекс PK его и обслуживает.
CREATE INDEX IF NOT EXISTS deal_addresses_stale_idx ON deal_addresses (fetched_at);

COMMENT ON TABLE deal_addresses IS
  'Кэш адресов объектов сделок из Битрикса (UF_ADDRESS_COORDS): карточка сделки, «объекты» заказчика, карта (задача 21.09)';
