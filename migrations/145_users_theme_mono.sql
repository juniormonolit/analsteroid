-- Третья тема «моно» (задача 2999, дизайн-система «Монолитика Glass», владелец
-- приложения Серёга): расширяет users.theme (миграция 070, CHECK theme IN ('light',
-- 'dark')) третьим значением — тёмное серое стекло с единственным синим акцентом,
-- палитра графиков сворачивается в серую шкалу, но статусы/тиры остаются цветными
-- (tokens/theme-mono.css пакета). Дефолт колонки не меняется (остаётся 'light').
--
-- Без этой миграции переключатель темы в ЛК всё равно способен ПОКАЗАТЬ mono
-- (data-theme применяется на клиенте оптимистично, до ответа сервера — см.
-- lib/hooks/useTheme.ts applyTheme()), но PATCH /api/me/theme будет падать на этом
-- CHECK-констрейнте, и выбор НЕ переживёт перезаход/другое устройство, пока миграция
-- не применена — ветку это ломает же, что видно по автодеплой-гарду (блокирует
-- деплой коммитов с новым migrations/*.sql до ручного применения).
--
-- БД: YC system (junibaseone на dev-стенде). НЕ применять локально/самостоятельно —
-- накатывает Артём вручную (владелец подтверждает по тому же процессу, что миграция 070).

DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'users_theme_check'
  ) THEN
    ALTER TABLE users DROP CONSTRAINT users_theme_check;
  END IF;

  ALTER TABLE users
    ADD CONSTRAINT users_theme_check
    CHECK (theme IN ('light', 'dark', 'mono'));
END $$;
