-- 184: дайджест не пишет неактивным аккаунтам. БД: system.
-- Владелец 09.09: «на неактивные аккаунты постоянно уходит „Не за что похвалить или
-- поругать" — смысла в этом спаме на неиспользуемые аккаунты нет». Ростер дайджеста —
-- активные по ОРГСТРУКТУРЕ (sa.org_resolved_hierarchy.is_active), а это не то же, что
-- «работает в Битриксе»: intake-аккаунты, роботы, ушедшие в декрет и т.п. активны в
-- структуре, но сделок/событий у них нет. Порог настраиваемый: столько дней без
-- единого события по сделкам (deal_events) и без новых сделок — дайджест не шлём.
ALTER TABLE digest_settings ADD COLUMN IF NOT EXISTS inactive_days int NOT NULL DEFAULT 30
  CHECK (inactive_days BETWEEN 1 AND 365);
COMMENT ON COLUMN digest_settings.inactive_days IS
  'Менеджер без событий по сделкам и без новых сделок столько дней — дайджест ему не отправляется (панель бота → Дайджест).';
