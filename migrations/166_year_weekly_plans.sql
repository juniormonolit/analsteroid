-- спец-отчёта «Данные по годам» (владелец 28.08: «планы по сделкам на 2026 год
-- возьми отсюда и заполни в отчёт» — файл «Данные по годам.xlsx»).
-- БД: YC system. Накат:
--   node migrations/run_local.mjs migrations/166_year_weekly_plans.sql
--
-- Зачем таблица: в приложении планов по КОЛИЧЕСТВУ сделок нет вообще —
-- manager_plans хранит только деньги (plan_shipments, план продаж =
-- shipments/plan_n). Конверсий и ср. чека в планах тоже нет. В ручном файле они
-- есть по каждой сущности и месяцу, поэтому храним отдельной таблицей.
-- Денежные планы отчёт по-прежнему берёт из manager_plans (решение владельца
-- 28.08 «план = месяц / 4») — два источника не смешиваем.
--
-- Единицы: metric='deals' — МЕСЯЧНЫЙ план (в файле недельная строка = месяц/4,
-- здесь восстановлено ×4; движок делит на 4 обратно, как деньги);
-- 'cr_sale'/'cr_ship' — доли (0.11 = 11%), 'avg_check' — рубли. Эти три —
-- уровневые: делить на 4 их нельзя, в неделю и месяц идут как есть.
--
-- Источник значений: строки «План» листа «2026», сущности сопоставлены как в
-- ENTITY_DEFS. Для «СПБ ИТОГО»/«МСК ИТОГО» плана по сделкам в файле нет —
-- посчитан как сумма компонентов (ОС+НЦ), тем же правилом, по которому в файле
-- считаются денежные ИТОГО (=J6+V6).

