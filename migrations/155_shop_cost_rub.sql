-- Себестоимость товара в рублях (задача владельца 05-06.08: «админ должен
-- задавать себестоимость в рублях, чтобы на дашборде экономики считать реальные
-- затраты; после ввода стоимости цена в MLT считается автоматом, но её можно
-- изменить»).
--
-- Курс берётся из badge_coin_settings.mlt_rub_rate (миграция 153, сейчас 5 ₽):
-- price_units = cost_rub / rate. Расчёт делает UI при вводе — сохраняется уже
-- готовая цена, чтобы изменение курса не переоценивало витрину задним числом.
--
-- СИСТЕМНАЯ БД (YC), вручную через migrations/run_system.mjs, ОТДЕЛЬНО на dev
-- (junibaseone) и prod (system).
-- DOWN: ALTER TABLE shop_items DROP COLUMN cost_rub;

ALTER TABLE shop_items
  ADD COLUMN IF NOT EXISTS cost_rub numeric CHECK (cost_rub IS NULL OR cost_rub >= 0);

COMMENT ON COLUMN shop_items.cost_rub IS
  'Себестоимость для компании в рублях. NULL — не задана (тогда дашборд оценивает затраты по цене продажи × курс, что завышает). Нематериальные позиции (отгул, обучение) могут иметь 0 — они стоят рабочего времени, а не денег.';
