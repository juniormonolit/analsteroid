-- Задача владельца 07.08.2026: кнопка «Фильтр сделок» рядом со «Сравнением»,
-- условия режут набор сделок всего отчёта. Владелец выбрал вариант «сохранять и
-- в ссылке, и в отчёте» — чтобы можно было завести постоянный «Отчёт по крупным
-- сделкам» и скинуть его РОПу ссылкой.
--
-- saved_reports — типизированная таблица без catch-all JSON-колонки, поэтому под
-- каждое новое свойство отчёта заводится своя колонка (так же добавлялись
-- column_groups в 024 и остальные). Формат значения — массив условий
-- [{field, op, value}], разбор и белый список полей — lib/metrics/dealFilters.ts.
--
-- DEFAULT '[]' + NOT NULL: у всех существующих отчётов фильтр пустой, то есть
-- поведение не меняется ни у одного сохранённого отчёта.

ALTER TABLE saved_reports
  ADD COLUMN IF NOT EXISTS deal_filters jsonb NOT NULL DEFAULT '[]'::jsonb;
