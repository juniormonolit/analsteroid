-- Migration 170: настройки отчёта «По периодам» сохраняются вместе с отчётом
-- БД: YC system (таблица saved_reports). Накат с ноутбука:
--   node migrations/run_local.mjs migrations/170_saved_reports_periods.sql
--
-- Задача владельца 09.08.2026: новый тип отчёта «По периодам» — строки не
-- менеджеры и не товарные группы, а сами периоды (день/неделя/месяц/квартал/год),
-- дрилл бакета уходит в менеджеров или товарные группы переключателем в шапке.
-- Движок — features/reports/engine/byPeriods.ts, роут — app/api/reports/by-periods.
--
-- saved_reports — типизированная таблица без catch-all JSON-колонки (см. коммент
-- миграции 162), поэтому под каждое новое свойство отчёта заводится своя колонка.
-- Здесь их три, ровно те, что задают «какой это отчёт по периодам»:
--   period_unit      — шаг группировки: day|week|month|quarter|year;
--   period_dimension — разрез дрилла: managers|product-groups (он же задаёт охват
--                      строки: в менеджерском считаются только сделки с
--                      ответственным, как в отчёте «По менеджерам»);
--   compare_mode     — база сравнения: prev (предыдущий такой же период) |
--                      yoy (тот же период год назад) | none. Обычного «периода
--                      сравнения» у этого отчёта нет: строки САМИ являются
--                      периодами, второй диапазон дублировал бы ось.
--
-- Все три NULLable без DEFAULT: у отчётов остальных типов они не имеют смысла и
-- остаются пустыми, поведение ни одного существующего отчёта не меняется. Дефолты
-- (month / managers / prev) подставляет клиент — см. applyPreset в SalesReportPage.
--
-- ВНИМАНИЕ ПО ПОРЯДКУ ВЫКАТКИ: код /api/saved-reports SELECT'ит эти колонки
-- поимённо, поэтому миграция обязана быть накатана ДО деплоя кода — иначе список
-- сохранённых отчётов упадёт у всех, а не только у нового типа.

ALTER TABLE saved_reports
  ADD COLUMN IF NOT EXISTS period_unit text,
  ADD COLUMN IF NOT EXISTS period_dimension text,
  ADD COLUMN IF NOT EXISTS compare_mode text;
