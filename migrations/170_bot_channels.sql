-- геймификации отношения не имеет и молчать не должен. Менять поведение можно
-- было только правкой start.sh на сервере с рестартом — то есть владелец без
-- разработчика не мог ни включить, ни выключить ничего.
--
-- ЧТО СТАЛО. Канал у каждого отправителя, флажок у каждого канала, всё в БД и
-- в админке. Разбиение НЕ по ботам, а ПО СМЫСЛУ сообщения: у «Аналитика» под
-- одним ботом живут и ежедневный отчёт владельцу, и «ты получил награду», и
-- вопрос РОПа по сделке — глушить их одним флагом и значило потерять нужное
-- вместе с ненужным.
--
-- ДЕФОЛТЫ ВОСПРОИЗВОДЯТ ТЕКУЩЕЕ СОСТОЯНИЕ, кроме одного намеренного изменения:
-- `call_control` включён — это прямая просьба владельца. Остальное владелец
-- включает сам в интерфейсе, когда решит; молча расчехлять каналы, которые
-- три недели молчали, нельзя — люди получат пачку писем «за прошлое».
--
-- СИСТЕМНАЯ БД (YC). 09.08.2026 применена ТОЛЬКО НА DEV (junibaseone).
-- DOWN: DROP TABLE bot_channels;

