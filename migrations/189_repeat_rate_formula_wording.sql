--
-- Вопрос владельца 03.09: «1965 / 6209 = 31 %, а в отчёте 28,6 % — почему?»
-- Он делил повторных на «Новые клиенты», а знаменатель формулы — «Клиенты с
-- отгрузкой» (все уникальные покупатели периода). Приписка из 185 «(новые +
-- повторные = все клиенты периода)» подталкивала ровно к этой ошибке: из-за
-- клиентов, купивших впервые И повторно в одном периоде, новые + повторные
-- БОЛЬШЕ, чем «все» (в срезе владельца пересечение ~1 300 клиентов).

BEGIN;

UPDATE metrics SET formula_human =
  '= «Купившие повторно» ÷ «Клиенты с отгрузкой» × 100. Знаменатель — ВСЕ уникальные покупатели периода, а не «Новые клиенты»: тот, кто купил впервые и тут же повторно, входит и в новых, и в повторных, но во «всех» — один раз, поэтому новые + повторные обычно больше, чем все'
 WHERE id = 'repeat_rate_clients';

COMMIT;
