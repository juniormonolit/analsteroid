-- Migration 172: медианные времена между заказами — в раздел «Клиенты», с движком
-- БД: YC analytics (таблица metrics). Накат с ноутбука:
--   node migrations/run_local.mjs migrations/172_client_time_metrics.sql --db=analytics
--
-- Вторая пачка метрик владельца (10.08.2026). Как и в первой, все четыре id уже
-- существовали в категории «Повторные» (ТЗ #1725) — и, как и три метрики из
-- первой пачки, были МЁРТВЫМИ: объявлены как external, но ни один движок их не
-- заполнял, колонки всегда были пустыми. Теперь их считает
-- features/reports/engine/clientMetrics.ts (fetchClientTimeMetrics).
--
-- ── ЧТО ИЗМЕНИЛОСЬ В ОПРЕДЕЛЕНИЯХ ────────────────────────────────────────────
--
-- 1. ЗАКАЗ ≠ ОТГРУЗКА. Владелец: «не учитывать интервал 1 день между заказами,
--    то есть считать такие заказы как 1 заказ». Отгрузки, идущие не дальше суток
--    друг от друга, склеиваются в один заказ; время заказа — первая отгрузка
--    склейки. Склейка цепная: отгрузки в 0:00, +20 ч и +40 ч — это ОДИН заказ.
--    Именно склейка, а не отбрасывание коротких интервалов: при отгрузках 1-го,
--    1-го и 11-го числа правильный ответ 10 дней, а не 9,5.
--
-- 2. «Между всеми заказами» раньше описывалось как медиана ПО КЛИЕНТАМ от их
--    среднего интервала ((последняя − первая)/(N−1)). Владелец просит медиану по
--    самим интервалам — так одна аномально долгая пауза не растворяется в
--    среднем по клиенту. Считаем по интервалам.
--
-- 3. «Разные категории» считаются по позициям сделки с исключением сервисных
--    групп (миграция 171, lib/metrics/serviceGroups.ts), а не по одной главной
--    группе. Заказ считается «новой категорией», если принёс клиенту группу,
--    которой в его прошлых заказах не было. «До второго заказа другой группы» —
--    первый такой интервал, «между заказами разных групп» — все.
--
-- 4. ПРИВЯЗКА К ПЕРИОДУ И СТРОКЕ: интервал относится туда, где стоит
--    ЗАКРЫВАЮЩИЙ его заказ. Только так метрика становится периодной («сколько
--    ждали те, кто вернулся в июле»). История клиента при этом читается целиком.
--
-- Названия приведены к «Медианное время…»: раньше они назывались «Среднее
-- время…», хотя в описании честно стояло «показываем медиану» — читатель верил
-- заголовку колонки, а не описанию, которое никто не открывает.
--
-- Живая проверка на июле 2026 (сверено с независимым пересчётом на JS, совпало
-- до третьего знака): до 2-го заказа 22,0 дня; между заказами 16,1; до 2-го
-- заказа другой категории 33,5; между заказами разных категорий 34,3.

BEGIN;

CREATE TABLE IF NOT EXISTS metrics_backup_172 AS SELECT * FROM metrics WHERE false;
INSERT INTO metrics_backup_172
  SELECT * FROM metrics
   WHERE id IN ('median_time_to_2nd', 'median_time_between_orders',
                'median_time_to_2nd_diff_cat', 'median_time_between_orders_diff_cat')
     AND NOT EXISTS (SELECT 1 FROM metrics_backup_172);

UPDATE metrics SET category = 'Клиенты', decimal_places = 1, is_hidden_in_ui = false,
  name_ru = 'Медианное время до второго заказа', name_short_ru = 'Мед. до 2-го',
  sort_order = 1415,
  description = 'Медиана числа дней между первым и вторым заказом клиента. Заказ — '
    || 'склейка отгрузок, идущих не дальше суток друг от друга (владелец: интервал '
    || 'в 1 день и меньше — это один заказ). Интервал относится к периоду, в котором '
    || 'стоит ВТОРОЙ заказ. Медиана, а не среднее: хвост долгих возвратов задирает '
    || 'среднее. В «Итого» не суммируется — там медиана по всей совокупности.'
  WHERE id = 'median_time_to_2nd';

UPDATE metrics SET category = 'Клиенты', decimal_places = 1, is_hidden_in_ui = false,
  name_ru = 'Медианное время между заказами', name_short_ru = 'Мед. между',
  sort_order = 1416,
  description = 'Медиана числа дней между соседними заказами клиента — по всем '
    || 'интервалам, а не по среднему на клиента (как было в ТЗ #1725). Заказ — '
    || 'склейка отгрузок в пределах суток. Интервал относится к периоду закрывающего '
    || 'его заказа. В «Итого» не суммируется.'
  WHERE id = 'median_time_between_orders';

UPDATE metrics SET category = 'Клиенты', decimal_places = 1, is_hidden_in_ui = false,
  name_ru = 'Медианное время до второго заказа другой товарной группы',
  name_short_ru = 'Мед. до др. группы', sort_order = 1417,
  description = 'Медиана числа дней от первого заказа клиента до первого заказа, '
    || 'принёсшего товарную группу, которой у него ещё не было. Сервисные группы '
    || '(перевозка, аренда спецтехники, для логистов, служебная, ошибка) новой '
    || 'категорией не считаются. В «Итого» не суммируется.'
  WHERE id = 'median_time_to_2nd_diff_cat';

UPDATE metrics SET category = 'Клиенты', decimal_places = 1, is_hidden_in_ui = false,
  name_ru = 'Медианное время между заказами разных товарных групп',
  name_short_ru = 'Мед. между др. группами', sort_order = 1418,
  description = 'Медиана числа дней между соседними заказами, каждый из которых '
    || 'принёс клиенту новую для него товарную группу. Сервисные группы исключены. '
    || 'В «Итого» не суммируется.'
  WHERE id = 'median_time_between_orders_diff_cat';

COMMIT;
