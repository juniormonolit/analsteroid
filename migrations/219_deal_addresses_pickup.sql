-- 219: «Париж» в адресе = САМОВЫВОЗ (правило владельца 21.09, дословно:
-- «если Париж — это самовывоз»).
--
-- Что в данных. Менеджеры пишут в адресное поле Битрикса «Париж» — так
-- называется точка самовывоза, — а геокодер пытается это понять и раскидывает
-- по улицам Вице-адмирала Падорина в Североморске, площади в Павловском
-- Посаде и даже по настоящему Парижу во Франции. На 21.09 таких сделок
-- 23 717 — это самая большая «точка» всей базы (одна только североморская
-- координата собрала 23 601 сделку и была первой в списке служебных).
--
-- Почему нужен отдельный признак, а не просто «служебная точка»: самовывоз —
-- это не мусор и не ошибка заполнения. Такая сделка ФИЗИЧЕСКИ не имеет адреса
-- доставки, поэтому её нельзя:
--   * считать объектом заказчика (иначе «строитель» из любого, кто дважды
--     забрал сам);
--   * ставить точкой на карту (её там нет);
--   * записывать менеджеру в «нет адреса» в дисциплине заполнения (упрёк не
--     по делу — адресу просто неоткуда взяться).
-- Зато её полезно СЧИТАТЬ ОТДЕЛЬНО: «самовывоз — N сделок» это нормальная
-- строка отчёта.
--
-- Правило распознавания: слово «париж» целиком, без учёта регистра
-- (\m…\M — границы слова). Прилагательные НЕ ловятся: «1-й Парижский проезд»
-- в Краснодаре и «улица Парижской Коммуны» — настоящие адреса доставки
-- (59 сделок), они остаются обычными объектами.

ALTER TABLE deal_addresses
  ADD COLUMN IF NOT EXISTS is_pickup boolean GENERATED ALWAYS AS (
    address IS NOT NULL AND address ~* '\mпариж\M'
  ) STORED;

CREATE INDEX IF NOT EXISTS deal_addresses_pickup_idx ON deal_addresses (is_pickup) WHERE is_pickup;

COMMENT ON COLUMN deal_addresses.is_pickup IS
  'Самовывоз: в адресе стоит «Париж» — название точки самовывоза, геокодер разносит его по случайным координатам (правило владельца 21.09)';
