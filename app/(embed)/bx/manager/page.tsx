import { redirect } from 'next/navigation';
import { getSession } from '@/lib/auth/session';

// Вход из локального приложения Битрикса (правка владельца 05.08: «в локальное
// приложение Битрикса надо выводить по сути /profile, сейчас там заглушка»).
//
// Раньше здесь жила ОТДЕЛЬНАЯ страница с одной карточкой менеджера. Пока ЛК был
// одной карточкой, это работало; после переезда кабинета на /profile с рельсой
// разделов (Движуха, Коллеги, Кошелёк, Награды, Заявки, Уведомления) внутри
// портала оставался огрызок: ссылки ведут на /profile/*, а CSP их фреймить не
// давал. Теперь портал имеет право фреймить /profile/* (см. next.config.ts), и
// этот адрес — просто вход: отдаём кабинет целиком, одна реализация на все точки
// входа. Сессию заводит /api/bitrix/app ДО этого редиректа.
export const metadata = { title: 'Мой кабинет — Монолитика' };

export default async function Page() {
  const session = await getSession();

  // Сессии нет — почти всегда браузер зарезал cookie в iframe (третьесторонний
  // контекст). Partitioned-cookie в обработчике решает это в Chrome/Edge/Firefox;
  // Safari может всё равно не пустить. Текст прежний: он объясняет человеку, что
  // делать, вместо пустого экрана.
  if (!session) {
    return (
      <div className="p-6 text-sm text-[var(--color-text-muted)] max-w-md mx-auto text-center">
        <p className="mb-2 font-semibold text-[var(--color-text)]">Не удалось открыть кабинет</p>
        <p>
          Браузер заблокировал вход внутри окна Битрикса. Попробуйте открыть портал
          в Chrome или в приложении Битрикс24 — там кабинет работает. Если не
          помогло, напишите администратору.
        </p>
      </div>
    );
  }

  // Аккаунт без привязки к Битриксу и «чью карточку показать» решает сам ЛК
  // (app/(app)/profile/page.tsx → resolveSelfCard) — дублировать эту логику
  // здесь больше не нужно: ровно из-за дубля файлы однажды разъехались
  // (забытый showBadges, задача 2764).
  redirect('/profile');
}
